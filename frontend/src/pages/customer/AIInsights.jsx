import { useState } from 'react';
import { getErrorMessage } from '../../api/client';
import { aiApi, metaApi } from '../../api/services';
import { Alert, Loader, StatCard } from '../../components/Common';
import { useApi } from '../../hooks/useApi';
import { formatCurrency, formatDateTime } from '../../utils/format';

const EXAMPLES = [
  'Summarize my last five orders.',
  'Which of my orders are still not delivered?',
  'How much did I spend this week?',
  'Which food items have I ordered most frequently?',
];

export default function AIInsights() {
  const { data: stats, loading: statsLoading } = useApi(() => aiApi.stats(), []);
  const { data: meta } = useApi(() => metaApi.get(), []);
  const [question, setQuestion] = useState('');
  const [conversation, setConversation] = useState([]);
  const [asking, setAsking] = useState(false);
  const [error, setError] = useState('');

  const ask = async (mode, q) => {
    if (asking) return;
    setError('');
    setAsking(true);
    try {
      const res = await aiApi.insights(mode, mode === 'question' ? q : undefined);
      setConversation((c) => [{ ...res, id: Date.now() }, ...c]);
      if (mode === 'question') setQuestion('');
    } catch (err) {
      const status = err.response?.status;
      let msg = getErrorMessage(err);
      if (status === 429) msg = `⏳ ${msg}`;
      setError(msg);
    } finally {
      setAsking(false);
    }
  };

  const submit = (e) => {
    e.preventDefault();
    if (question.trim()) ask('question', question.trim());
  };

  return (
    <div className="container page">
      <h1>✨ AI Order Insights</h1>
      <p className="muted">Ask questions about <strong>your own</strong> order history. Answers are generated by AI using only your orders.</p>

      {statsLoading ? <Loader /> : stats && (
        <>
          <div className="stats-grid">
            <StatCard label="Orders placed" value={stats.total_orders} />
            <StatCard label="Spent this week" value={formatCurrency(stats.spent_this_week)} accent="green" />
            <StatCard label="Avg. order value" value={formatCurrency(stats.average_order_value)} />
            <StatCard label="Not yet delivered" value={stats.not_delivered_order_ids.length} accent="blue"
              hint={stats.not_delivered_order_ids.length ? `#${stats.not_delivered_order_ids.join(', #')}` : ''} />
          </div>
          {stats.most_ordered_items.length > 0 && (
            <p className="small"><span className="muted">Your favourites:</span> {stats.most_ordered_items.map((i) => `${i.name} (×${i.quantity})`).join(', ')}</p>
          )}
        </>
      )}

      {meta && !meta.ai_enabled && (
        <Alert type="info">The AI service isn’t configured on this server (OPENAI_API_KEY missing). The statistics above still work.</Alert>
      )}

      <section className="card ai-box">
        <form onSubmit={submit} className="ai-form">
          <input
            value={question} onChange={(e) => setQuestion(e.target.value)} maxLength={500}
            placeholder="Ask anything about your orders…" aria-label="Your question" disabled={asking}
          />
          <button className="btn btn-primary" disabled={asking || !question.trim()}>Ask</button>
          <button type="button" className="btn btn-ghost" disabled={asking} onClick={() => ask('summary')}>Summarize my orders</button>
        </form>
        <div className="chips">
          {EXAMPLES.map((q) => (
            <button key={q} type="button" className="chip chip-btn" disabled={asking} onClick={() => ask('question', q)}>{q}</button>
          ))}
        </div>
        <Alert onClose={() => setError('')}>{error}</Alert>
        {asking && <Loader text="Analysing your orders…" />}
      </section>

      <div className="ai-answers">
        {conversation.map((c) => (
          <article key={c.id} className="card ai-answer">
            <p className="ai-q">🙋 {c.mode === 'summary' ? 'Summary of my orders' : c.question}</p>
            <div className="ai-a">{c.answer}</div>
            <p className="muted small">Based on {c.orders_considered} order(s) · {c.model} · {formatDateTime(c.generated_at)}</p>
          </article>
        ))}
      </div>
    </div>
  );
}
